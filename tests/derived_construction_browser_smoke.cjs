  await page.locator('#question').fill('圆x²+y²=9，点P(0,0)，求在点P处的切线方程。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('没有把其它方程冒充为切线'));
