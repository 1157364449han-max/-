  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('(x-1/2)²/(9/4)+y²=1'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  locus=scene.objects.find(item=>item.role==='derived_locus');
  assert.deepEqual({equation:locus.equation,kind:locus.kind,conicType:locus.conicType,h:locus.h,k:locus.k,a:locus.a,b:locus.b,refs:locus.refs,construction:locus.construction,part:locus.part},onlineLocus,'在线与离线轨迹曲线契约必须一致');
