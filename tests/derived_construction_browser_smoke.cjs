  assert.match(await page.locator('#layers').innerText(),/P 点切线 · 推导/);
  assert.match(await page.locator('#solution').innerText(),/局部代数核验通过/);

  await page.locator('#question').fill('圆x²+y²=25，点A(3,4)、B(-4,3)在圆上，证明A、B两点处的切线互相垂直。');
  await page.locator('#solveButton').click();
