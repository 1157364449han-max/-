  assert.notEqual(pairTangents[0].pointRef,pairTangents[1].pointRef,'两条切线必须绑定两个不同切点');
  assert.match(await page.locator('#layers').innerText(),/A 点切线 · 推导/);
  assert.match(await page.locator('#layers').innerText(),/B 点切线 · 推导/);
  await page.locator('.verification-details summary').click();
  assert.match(await page.locator('#solution').innerText(),/通过 · 两切线垂直关系/);
  const onlineTangentPair=pairTangents.map(line=>({point:line.point,equation:line.equation,pointRef:line.pointRef,refs:line.refs,exact:line.exact,construction:line.construction,part:line.part}));

  await page.locator('#question').fill('圆x²+y²=25，A(3,4)、B(-4,3)在圆上，证明A点和B点处的切线互相垂直。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('方向向量点积为 0'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  assert.deepEqual(new Set(scene.lines.filter(line=>line.role==='tangent').map(line=>line.point)),new Set(['A','B']),'带“点”字后缀的复数表述也必须建立两条切线');

  await page.locator('#question').fill('已知椭圆x²/4+y²/3=1，点P(1,3/2)在椭圆上，求在点P处的法线方程。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('4x-2y-1=0'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  let normal=scene.lines.find(line=>line.role==='normal');
  assert(normal,'答案所得法线必须进入画板场景');
  assert.equal(normal.equation,'4x-2y-1=0');
  assert.equal(normal.source,'derived');
  assert.equal(normal.construction.schema,'dongjiexi-construction/v1');
  assert.equal(normal.construction.type,'normal_at');
  assert.match(await page.locator('#layers').innerText(),/P 点法线 · 推导/);
  assert.match(await page.locator('#solution').innerText(),/局部代数核验通过/);
  const onlineNormal={equation:normal.equation,exact:normal.exact,construction:normal.construction};

  await page.locator('#question').fill('已知圆x²+y²=9，点P(3,4)，l:y=1，m:x=0，求点P到l的垂足H的坐标。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('H(3,1)'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  let foot=scene.objects.find(item=>item.role==='perpendicular_foot');
  assert(foot,'答案所得垂足必须进入画板构造图');
  assert.deepEqual(foot.exact,{x:'3',y:'1'});
  assert.equal(foot.source,'derived');
  assert.equal(foot.op,'foot');
  assert.equal(foot.construction.type,'perpendicular_foot');
  assert.equal(scene.lines.find(line=>line.id===foot.construction.inputs.line)?.label,'l','多条直线存在时必须按名称选择 l');
  assert.equal(scene.showDynamic,false,'有明确方程的直线不能再生成无关旋转动直线');
  assert.equal(scene.dynamicLine,false,'浏览器导出的 Python 兼容别名必须保持同一语义');
  assert.match(await page.locator('#layers').innerText(),/H · 推导/);
  assert.match(await page.locator('#solution').innerText(),/局部代数核验通过/);
