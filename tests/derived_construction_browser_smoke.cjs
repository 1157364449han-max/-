  await page.locator('#question').fill('已知椭圆x²/4+y²/3=1，点P(1,3/2)在椭圆上，求椭圆在点P处的切线方程。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('x+2y-4=0'));
  let scene=JSON.parse(await page.locator('#sceneJson').inputValue());
