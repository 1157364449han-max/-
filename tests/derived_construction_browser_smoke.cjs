  assert.deepEqual({equation:normal.equation,exact:normal.exact,construction:normal.construction},onlineNormal,'在线与离线法线契约必须一致');

  await page.locator('#question').fill('已知椭圆x²/4+y²/3=1，点P(1,3/2)在椭圆上，求在点P处的法线。（1）写出法线方程；（2）求离心率。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('4x-2y-1=0'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  normal=scene.lines.find(line=>line.role==='normal');
  assert.equal(normal.part,1,'第一小问之前出现的派生要求必须绑定最近的下一小问，不能成为全局核验对象');

  await page.locator('#question').fill('已知圆x²+y²=9，点P(3,4)，l:y=1，m:x=0，求点P到l的垂足H的坐标。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('H(3,1)'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  foot=scene.objects.find(item=>item.role==='perpendicular_foot');
  assert.deepEqual({exact:foot.exact,construction:foot.construction},onlineFoot,'在线与离线垂足契约必须一致');

  await page.locator('#question').fill('圆x²+y²=9与直线y=0交于A、B，求AB的长度和中点坐标。');
  await page.locator('#solveButton').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('弦长 |AB|=6'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  const offlineChord=scene.objects.filter(item=>['line_conic_intersection','derived_chord','derived_midpoint'].includes(item.role)).map(item=>({role:item.role,label:item.label,refs:item.refs,exact:item.exact,construction:item.construction,part:item.part}));
  assert.deepEqual(offlineChord,onlineChord,'在线与离线交点、弦和中点契约必须一致');

  await page.locator('#question').fill('圆x²+y²=9与直线y=0交于A、B。（1）求A、B坐标；（2）求圆在A点处的切线方程。');
  await page.locator('#solveButton').click();
  await page.locator('[data-study-part="2"]').click();
  await page.waitForFunction(() => document.querySelector('#solution')?.textContent.includes('x+3=0'));
  scene=JSON.parse(await page.locator('#sceneJson').inputValue());
  tangent=scene.lines.find(line=>line.role==='tangent');
  assert.deepEqual({equation:tangent.equation,pointRef:tangent.pointRef,refs:tangent.refs,exact:tangent.exact,construction:tangent.construction,part:tangent.part},onlineComputedTangent,'在线与离线的计算点切线契约必须一致');

  await page.locator('#question').fill('已知椭圆x²/9+y²/4=1，点P为椭圆上的动点，点Q(1,0)，M为线段PQ的中点，求点M的轨迹方程并画出轨迹。');
